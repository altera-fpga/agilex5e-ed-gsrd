#ifndef __QOS_GENERATOR_H__
#define __QOS_GENERATOR_H__

#include <stdint.h>

#define CCU_DMI0_QOS_GEN_BASE_ADDR 0x18001280
#define CCU_DMI1_QOS_GEN_BASE_ADDR 0x18001300
#define TBU2NOC_QOS_GEN_BASE_ADDR 0x18001380
#define DMA_QOS_GEN_BASE_ADDR 0x10D24080

#define PRIORITY_OFF 0x08
#define MODE_OFF 0x0C
#define BANDWIDTH_OFF 0x10
#define SATURATION_OFF 0x14
#define EXTCONTROL_OFF 0x18

#define CCU_DMI0_QOS_PRIORITY_REG_ADDR (CCU_DMI0_QOS_GEN_BASE_ADDR + PRIORITY_OFF)
#define CCU_DMI0_QOS_MODE_REG_ADDR (CCU_DMI0_QOS_GEN_BASE_ADDR + MODE_OFF)
#define CCU_DMI0_QOS_BANDWIDTH_REG_ADDR (CCU_DMI0_QOS_GEN_BASE_ADDR + BANDWIDTH_OFF)
#define CCU_DMI0_QOS_SATURATION_REG_ADDR (CCU_DMI0_QOS_GEN_BASE_ADDR + SATURATION_OFF)
#define CCU_DMI0_QOS_EXTCONTROL_REG_ADDR (CCU_DMI0_QOS_GEN_BASE_ADDR + EXTCONTROL_OFF)

#define CCU_DMI1_QOS_PRIORITY_REG_ADDR (CCU_DMI1_QOS_GEN_BASE_ADDR + PRIORITY_OFF)
#define CCU_DMI1_QOS_MODE_REG_ADDR (CCU_DMI1_QOS_GEN_BASE_ADDR + MODE_OFF)
#define CCU_DMI1_QOS_BANDWIDTH_REG_ADDR (CCU_DMI1_QOS_GEN_BASE_ADDR + BANDWIDTH_OFF)
#define CCU_DMI1_QOS_SATURATION_REG_ADDR (CCU_DMI1_QOS_GEN_BASE_ADDR + SATURATION_OFF)
#define CCU_DMI1_QOS_EXTCONTROL_REG_ADDR (CCU_DMI1_QOS_GEN_BASE_ADDR + EXTCONTROL_OFF)

#define TBU2NOC_QOS_PRIORITY_REG_ADDR (TBU2NOC_QOS_GEN_BASE_ADDR + PRIORITY_OFF)
#define TBU2NOC_QOS_MODE_REG_ADDR (TBU2NOC_QOS_GEN_BASE_ADDR + MODE_OFF)
#define TBU2NOC_QOS_BANDWIDTH_REG_ADDR (TBU2NOC_QOS_GEN_BASE_ADDR + BANDWIDTH_OFF)
#define TBU2NOC_QOS_SATURATION_REG_ADDR (TBU2NOC_QOS_GEN_BASE_ADDR + SATURATION_OFF)
#define TBU2NOC_QOS_EXTCONTROL_REG_ADDR (TBU2NOC_QOS_GEN_BASE_ADDR + EXTCONTROL_OFF)

#define DMA_QOS_PRIORITY_REG_ADDR (DMA_QOS_GEN_BASE_ADDR + PRIORITY_OFF)
#define DMA_QOS_MODE_REG_ADDR (DMA_QOS_GEN_BASE_ADDR + MODE_OFF)
#define DMA_QOS_BANDWIDTH_REG_ADDR (DMA_QOS_GEN_BASE_ADDR + BANDWIDTH_OFF)
#define DMA_QOS_SATURATION_REG_ADDR (DMA_QOS_GEN_BASE_ADDR + SATURATION_OFF)
#define DMA_QOS_EXTCONTROL_REG_ADDR (DMA_QOS_GEN_BASE_ADDR + EXTCONTROL_OFF)

void configure_qos_generator(uintptr_t register_addr, uint32_t qos_value);

#endif /* __QOS_GENERATOR_H__ */
