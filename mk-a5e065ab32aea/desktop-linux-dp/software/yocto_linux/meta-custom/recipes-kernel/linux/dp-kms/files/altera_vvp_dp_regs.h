/*
 * altera_vvp_dp_regs.h - Register map for the Altera Agilex GHRD
 *                            DisplayPort fabric subsystem.
 *
 * Physical memory layout (lwh2f base 0x2000_0000):
 *
 *   0x2003_0000  DP TX core          (DisplayPort TX IP, span 0x2000)
 *   0x2003_0D40  AXI2CV mode-bank    (sub-window inside DP TX)
 *   0x2003_5000  Clock PIO           (dp_source_pio_board, span 0x10)
 *   0x2002_0000  VFR CSR             (Altera VVP VFR, span 0x200)
 *
 * All offsets are BYTE offsets from their respective base.
 */
#ifndef ALTERA_VVP_DP_REGS_H
#define ALTERA_VVP_DP_REGS_H

/* ---- DP TX core physical window ------------------------------------------ */
#define DPTX_PHYS_BASE 0x20030000UL
#define DPTX_SPAN 0x2000UL

/* ---- AXI-Stream-to-image video interface (altera_dp_axi_2_im) ------------
 *
 * Quartus 26.3 (build >= ~55) replaced the old intel_axi2cv "clocked video"
 * block (mode-bank + MODE_MATCH poll, formerly at DPTX+0xD40) with the
 * altera_dp_axi_2_im "AXIS ingest throttle" (DP IP change: "Update AXI
 * passthrough to use new AXIS ingest throttle"). When TX_AXIS_VIDEOIF_EN=1
 * (this design) the DP TX video path now uses this module.
 *
 * It exposes just five word registers, based at the DP source AXI offset
 * (AXI_OFFSET = word 0x300 => byte 0xC00 within the DP TX window). There is
 * NO user mode bank, NO VALID commit and NO MODE_MATCH handshake to poll.
 *
 * Register values (H counts are per pixels-in-parallel because the stream
 * carries AXI2IM_PIP pixels per beat; SYSCLOCKS is in tx_axi4s_clk cycles):
 *   HACTIVE   = h_active / PIP
 *   HTOTAL    = h_total  / PIP
 *   VACTIVE   = v_active
 *   VTOTAL    = v_total
 *   SYSCLOCKS = tx_axi4s_clk (Hz) / (fps * v_total)  = clocks per video line.
 *               tx_axi4s_clk is the full pixel clock (148.5 MHz for 1080p60,
 *               NOT divided by PIP), so this equals h_total (e.g. 2200).
 */
#define AXI2IM_BASE 0x0C00
#define AXI2IM_HACTIVE (AXI2IM_BASE + 0x00) /* H active / PIP                 */
#define AXI2IM_HTOTAL (AXI2IM_BASE + 0x04) /* H total  / PIP                 */
#define AXI2IM_VACTIVE (AXI2IM_BASE + 0x08) /* V active lines                 */
#define AXI2IM_VTOTAL (AXI2IM_BASE + 0x0C) /* V total lines                  */
#define AXI2IM_SYSCLOCKS (AXI2IM_BASE + 0x10) /* tx_axi4s_clk cycles per line */

/* Pixels carried per AXI-stream beat (TX_PIXELS_PER_CLOCK / DP_TX_PIP). */
#define AXI2IM_PIP 4

/* ---- DP TX Main Stream Attributes (MSA) ---------------------------------
 *
 * On the AXIS/image path the DP TX no longer auto-measures the video timing
 * (the old clocked-video CVO did). Software must program the MSA so the sink
 * receives valid attributes, otherwise the monitor stays black. Byte offsets
 * = DP TX word index << 2 (DPTX0_REG_MSA_* from the DP IP register map).
 */
#define MSA_HTOTAL 0x88 /* word 0x22: horizontal total          */
#define MSA_VTOTAL 0x8C /* word 0x23: vertical total            */
#define MSA_HSP 0x90 /* word 0x24: horizontal sync polarity  */
#define MSA_HSW 0x94 /* word 0x25: horizontal sync width     */
#define MSA_HSTART 0x98 /* word 0x26: h sync+back-porch to active */
#define MSA_VSTART 0x9C /* word 0x27: v sync+back-porch to active */
#define MSA_VSP 0xA0 /* word 0x28: vertical sync polarity    */
#define MSA_VSW 0xA4 /* word 0x29: vertical sync width       */
#define MSA_HWIDTH 0xA8 /* word 0x2a: horizontal active pixels  */
#define MSA_VHEIGHT 0xAC /* word 0x2b: vertical active lines     */
/* MISC0 (word 0x2c, byte 0xB0) is auto-generated by the DP TX - not written. */

/* ---- Clock PIO (dp_source_pio_board) ------------------------------------- */
#define CLK_PIO_PHYS_BASE 0x20035000UL
#define CLK_PIO_SPAN 0x10UL
#define CLK_PIO_DATA 0x00 /* write divide-by-(N+1) value        */
#define CLK_PIO_DIV_DEFAULT 3 /* divide-by-4                        */

/* ---- VFR CSR (Altera VVP Video Frame Reader) ------------------------------ */
#define VFR_PHYS_BASE 0x20020000UL
#define VFR_SPAN 0x200UL

/* Identity/capability (read-only) */
#define VFR_VID_PID 0x000
#define VFR_LITE_MODE 0x008
#define VFR_MAX_BUFFER_SETS 0x010
#define VFR_MAX_HEIGHT 0x014
#define VFR_MAX_WIDTH 0x018
#define VFR_NUM_COLOR_PLANES 0x020
#define VFR_PIXELS_IN_PARALLEL 0x024
#define VFR_PACKING 0x028
#define VFR_VID_PID_EXPECT 0x6AF7024Au

/* Interrupt */
#define VFR_IRQ_CONTROL 0x100
#define VFR_IRQ_STATUS 0x104

/* Status / run control */
#define VFR_STATUS 0x140
#define VFR_STATUS_OUTPUTTING BIT(0)
#define VFR_STATUS_PENDING BIT(1)
#define VFR_LAST_BUFFER_READ 0x144
#define VFR_COMMIT 0x190 /* write 1 = latch staged config      */
#define VFR_NUM_BUFFER_SETS 0x194
#define VFR_BUFFER_MODE 0x198 /* 0=single-set 1=cycle-all           */
#define VFR_BUFFER_MODE_SINGLE 0
#define VFR_BUFFER_MODE_CYCLE 1
#define VFR_STARTING_BUFFER_SET 0x19C
#define VFR_RUN 0x1A0
#define VFR_RUN_STOP 0
#define VFR_RUN_GO BIT(0)
#define VFR_RUN_SINGLE_SHOT BIT(1)
#define VFR_RUN_FREE_RUNNING VFR_RUN_GO
#define VFR_FSYNC_PULSE_MODE 0x1A4

/* Per-buffer-set bank: base 0x1B0, stride 0x40 */
#define VFR_BUFSET_BASE 0x1B0
#define VFR_BUFSET_STRIDE 0x40
#define VFR_BUF_BASE 0x00 /* DDR physical base (32-bit)         */
#define VFR_BUF_NUM_BUFFERS 0x04
#define VFR_BUF_INTER_BUF_OFF 0x08 /* bytes between buffers              */
#define VFR_BUF_INTER_LINE_OFF 0x0C /* stride: bytes per line             */
#define VFR_BUF_WIDTH 0x10
#define VFR_BUF_HEIGHT 0x14
#define VFR_BUF_INTERLACE 0x18
#define VFR_BUF_COLORSPACE 0x1C
#define VFR_BUF_SUBSAMPLING 0x20 /* 3 = 4:4:4                          */
#define VFR_BUF_COSITING 0x24
#define VFR_BUF_BPS 0x28 /* bits per sample                    */
#define VFR_BUF_FIELD_COUNT 0x2C
#define VFR_SUBSAMPLING_444 3

/* Absolute byte offset of field f within buffer set n */
#define VFR_BUF(n, f) (VFR_BUFSET_BASE + (n) * VFR_BUFSET_STRIDE + (f))

/* VFR status poll budget */
#define VFR_STATUS_TRIES 50
#define VFR_STATUS_POLL_US 2000

/* Bytes per pixel (XRGB8888) */
#define DP_BYTES_PER_PIXEL 4

/*
 * VFR framebuffer line-stride alignment.
 *
 * The VFR reads the framebuffer over the coherent F2H path as a series of
 * 1024-byte (256-pixel) AXI bursts.  If the per-line stride is not an
 * integer multiple of this burst size, the final partial burst of each line
 * and the mid-burst line wrap corrupt pixel data, producing a periodic
 * horizontal-hatch / vertical-banding artifact (visible on any content that
 * varies line-to-line).  A burst-aligned stride eliminates it completely.
 *
 * Example: 1920 * 4 = 7680 B = 7.5 bursts -> artifact;
 *          ALIGN(7680, 1024) = 8192 B = 8 bursts -> clean.
 */
#define VFR_STRIDE_ALIGN 1024

/* DP TX register byte offsets (DP TX core word register index * 4). */
#define DPTX_OFF_TX_CONTROL 0x00u /* TX_CONTROL = word 0                */
#define DPTX_OFF_TX_STATUS 0x04u /* TX_STATUS  = word 1                */

/*
 * TX_CONTROL[3:0] = video control. Bit 2 (0x04) sends the video idle pattern;
 * clearing the low nibble enables active video. Toggling idle->active latches
 * newly-written MSA (matches btc_dptx_video_enable()).
 */
#define TX_CONTROL_VID_MASK 0x0Fu
#define TX_CONTROL_VID_IDLE 0x04u

/* DP TX link training */
#define TX_STATUS_HPD_MASK 0x04u /* bit 2 of TX_STATUS                */

/* =========================================================================
 * Native DisplayPort link-training register map (drm_dp_helper path)
 *
 * The DP TX core is word-addressed (register N = byte N*4).  These byte
 * offsets and bit layouts are hardware facts from the DP TX core register
 * map (UG-683273 §10), used by the native drm_dp_helper link-training path.
 * =========================================================================*/

/* Byte offset of DP TX word register N (index << 2). */
#define DPTX_WORD(n) ((n) << 2)

/* Per-lane drive settings: DPTX_REG_PRE_VOLT0..3 = words 0x10..0x13. */
#define DPTX_OFF_PRE_VOLT(lane) DPTX_WORD(0x10u + (lane))
/* Transceiver reconfigure trigger: DPTX_REG_RECONFIG = word 0x14. */
#define DPTX_OFF_RECONFIG DPTX_WORD(0x14u)
#define DPTX_RECONFIG_LINK 2u /* apply link config (GXB reconfig)   */
#define DPTX_RECONFIG_DRIVE 1u /* apply swing/pre-emphasis settings  */
#define DPTX_RECONFIG_WAIT_US 60000u /* GXB reconfig settle budget    */

/* PRE_VOLT payload: (pre_emphasis << 2) | voltage_swing, per lane. */
#define DPTX_PRE_VOLT(pre, volt) (((pre) << 2) | ((volt) & 0x3u))

/* DPTX_REG_TX_CONTROL (word 0) bit fields. */
#define TX_CTRL_PATTERN_MASK 0x0000001Fu /* [4:0]  local pattern source  */
#define TX_CTRL_LANE_SHIFT 5u
#define TX_CTRL_LANE_MASK 0x000003E0u /* [9:5]  lane count            */
#define TX_CTRL_CODING_SHIFT 10u
#define TX_CTRL_CODING_MASK 0x00000C00u /* [11:10] channel coding      */
#define TX_CTRL_PRECODE_DISABLE 0x00020000u /* [17] 128b/132b precoding */
#define TX_CTRL_ENHANCED_FRAME 0x00080000u /* [19] enhanced framing     */
#define TX_CTRL_RATE_SHIFT 21u
#define TX_CTRL_RATE_MASK 0x1FE00000u /* [28:21] link rate (DPCD BW)  */

/* TX_CONTROL pattern-source encodings (DPTX_REG_TX_CONTROL[4:0]). */
#define TX_PATTERN_NORMAL 0x0u /* video / scrambled data            */
#define TX_PATTERN_TP1 0x1u
#define TX_PATTERN_TP2 0x2u
#define TX_PATTERN_TP3 0x3u
#define TX_PATTERN_IDLE 0x4u
#define TX_PATTERN_TP4 0x7u

/* TX_CONTROL channel-coding field value for 8b/10b (HBR/HBR2). */
#define TX_CODING_8B10B 0x1u

/* AUX channel controller: DPTX_REG_AUX_CONTROL/COMMAND/BYTE0..18/RESET. */
#define DPTX_OFF_AUX_CONTROL DPTX_WORD(0x100u)
#define DPTX_OFF_AUX_COMMAND DPTX_WORD(0x101u)
#define DPTX_OFF_AUX_BYTE(n) DPTX_WORD(0x102u + (n))
#define DPTX_OFF_AUX_RESET DPTX_WORD(0x117u)

#define AUX_CTRL_READY 0x40000000u /* [30] controller idle/ready        */
#define AUX_CTRL_DONE 0x80000000u /* [31] reply received               */
#define AUX_CTRL_LEN_MASK 0x0000001Fu /* [4:0] message length (reply)   */

/*
 * AUX_COMMAND request nibble (write) and reply nibble (read, bits [7:4]).
 * The core packs the DP request code into COMMAND[7:4] identically for native
 * DPCD and I2C-over-AUX, i.e. HW command = (drm_request & 0xF) << 4.
 */
#define AUX_CMD_NATIVE_WRITE 0x80u
#define AUX_CMD_NATIVE_READ 0x90u
#define AUX_REPLY_MASK 0xF0u

/*
 * Reply decoding.  The native/AUX-layer reply lives in bits [5:4]; an
 * I2C-over-AUX transaction adds a second (I2C-layer) reply in bits [7:6].
 */
#define AUX_AUX_REPLY_MASK 0x30u /* native/AUX-layer reply mask [5:4] */
#define AUX_REPLY_ACK 0x00u
#define AUX_REPLY_NACK 0x10u
#define AUX_REPLY_DEFER 0x20u
#define AUX_I2C_REPLY_MASK 0xC0u /* I2C-layer reply mask [7:6] */
#define AUX_I2C_REPLY_ACK 0x00u
#define AUX_I2C_REPLY_NACK 0x40u
#define AUX_I2C_REPLY_DEFER 0x80u

/* AUX message framing: 4 header bytes (cmd + addr_hi + addr_lo + len). */
#define AUX_HDR_BYTES 4u
#define AUX_ADDR_ONLY_BYTES 3u /* I2C address-only probe (no len byte) */
#define AUX_MAX_PAYLOAD 16u
#define AUX_READY_TIMEOUT_US 2000u
#define AUX_REPLY_TIMEOUT_US 3000u

#endif /* ALTERA_VVP_DP_REGS_H */
